// Not run while building M5. Supply a disposable database with pgvector >= 0.8 and schema privileges:
// ENSEMUS_RECALL_DATABASE_URL=... ENSEMUS_RECALL_ALLOW_SCRATCH=1 pnpm exec vitest run --project measure tests/measure/knowledge-recall.measure.ts
// No product table is read or written. The one generated schema is dropped in finally.
// Settings checked against https://github.com/pgvector/pgvector#iterative-index-scans (2026-11-06).
import { randomUUID } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import pg from 'pg';
import { describe, expect, it } from 'vitest';

const DIMENSION = 32;
const TENANT_SIZES = [1_000, 10_000, 50_000];
const SELECTIVITIES = [1, 10, 50];
const WARMUP = 5,
  SAMPLES = 50,
  K = 10;
const schema = `knowledge_recall_${randomUUID().replaceAll('-', '')}`;
// Only identifiers generated by this file enter SQL text. Values always travel as parameters.
const table = `"${schema}"."items"`;
const indexName = 'items_hnsw';
const enabled = process.env.ENSEMUS_RECALL_ALLOW_SCRATCH === '1';
const url = process.env.ENSEMUS_RECALL_DATABASE_URL;
type Sample = {
  rows: number;
  aclPercent: number;
  recallAt10: number;
  exact: ReturnType<typeof latency>;
  hnsw: ReturnType<typeof latency>;
};

function latency(values: number[]) {
  const sorted = values.toSorted((a, b) => a - b);
  const at = (p: number) =>
    sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * p) - 1)] ?? 0;
  return { samples: sorted.length, p50Ms: at(0.5), p95Ms: at(0.95) };
}

function queryVector(seed: number) {
  let state = seed;
  return JSON.stringify(
    Array.from({ length: DIMENSION }, () => {
      state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
      return state / 2147483647.5 - 1;
    }),
  );
}

describe('generated exact versus HNSW recall under an ACL filter', () => {
  it.skipIf(!enabled || !url)(
    'measures the isolated scratch schema and writes JSON evidence',
    async () => {
      const client = new pg.Client({ connectionString: url });
      await client.connect();
      const samples: Sample[] = [];
      let created = false;
      try {
        const version = await client.query<{ extversion: string }>(
          "select extversion from pg_extension where extname='vector'",
        );
        expect(version.rows[0]?.extversion).toMatch(/^0\.(?:[89]|[1-9]\d)\.|^[1-9]\d*\./);
        await client.query(`create schema "${schema}"`);
        created = true;
        await client.query(
          `create table ${table} (id bigserial primary key, tenant integer not null, acl_bucket integer not null, embedding vector(${DIMENSION}) not null)`,
        );
        const query = `select id::text from ${table} where tenant=$1 and acl_bucket < $2 order by embedding <=> $3::vector limit ${K}`;
        const run = async (approximate: boolean, percent: number, vector: string) => {
          await client.query('begin');
          try {
            if (approximate) {
              await client.query("set local hnsw.iterative_scan = 'strict_order'");
              await client.query('set local hnsw.ef_search = 100');
              await client.query('set local hnsw.max_scan_tuples = 100000');
              await client.query('set local hnsw.scan_mem_multiplier = 4');
              await client.query('set local enable_seqscan = off');
            } else {
              await client.query('set local enable_indexscan = off');
              await client.query('set local enable_bitmapscan = off');
            }
            const start = performance.now();
            const result = await client.query<{ id: string }>(query, [1, percent, vector]);
            const ms = performance.now() - start;
            await client.query('commit');
            return { ids: result.rows.map((row) => row.id), ms };
          } catch (error) {
            await client.query('rollback');
            throw error;
          }
        };
        for (const size of TENANT_SIZES) {
          await client.query(`drop index if exists "${schema}"."${indexName}"`);
          await client.query(`truncate ${table} restart identity`);
          // Independent generated vectors in two tenants. ACL buckets model 1%, 10%, and 50% reach.
          await client.query(
            `insert into ${table} (tenant,acl_bucket,embedding)
          select tenant, n % 100,
                 array(select ((('x'||substr(md5(tenant::text||':'||n::text||':'||d::text),1,8))::bit(32)::bigint)::double precision / 2147483647.5) - 1
                         from generate_series(1,${DIMENSION}) d)::vector
            from generate_series(1,$1::integer) n cross join generate_series(1,2) tenant`,
            [size],
          );
          await client.query(
            `create index "${indexName}" on ${table} using hnsw (embedding vector_cosine_ops)`,
          );
          await client.query(`analyze ${table}`);
          await client.query('begin');
          try {
            await client.query('set local enable_seqscan = off');
            await client.query("set local hnsw.iterative_scan = 'strict_order'");
            const plan = await client.query(`explain (format json) ${query}`, [
              1,
              10,
              queryVector(1),
            ]);
            expect(JSON.stringify(plan.rows)).toContain(indexName);
          } finally {
            await client.query('rollback');
          }
          for (const percent of SELECTIVITIES) {
            const exactMs: number[] = [],
              hnswMs: number[] = [],
              recall: number[] = [];
            for (let i = 0; i < WARMUP + SAMPLES; i++) {
              const vector = queryVector(1000 + i);
              const exact = await run(false, percent, vector);
              const approximate = await run(true, percent, vector);
              expect(exact.ids).toHaveLength(K);
              expect(new Set(approximate.ids).size).toBe(approximate.ids.length);
              if (i >= WARMUP) {
                const truth = new Set(exact.ids);
                recall.push(approximate.ids.filter((id) => truth.has(id)).length / K);
                exactMs.push(exact.ms);
                hnswMs.push(approximate.ms);
              }
            }
            samples.push({
              rows: size,
              aclPercent: percent,
              recallAt10: recall.reduce((a, b) => a + b, 0) / recall.length,
              exact: latency(exactMs),
              hnsw: latency(hnswMs),
            });
          }
        }
        const evidence = {
          measuredAt: new Date().toISOString(),
          vectorVersion: version.rows[0]!.extversion,
          dimension: DIMENSION,
          tenants: 2,
          samples,
          settings: {
            iterativeScan: 'strict_order',
            efSearch: 100,
            maxScanTuples: 100000,
            scanMemMultiplier: 4,
          },
          note: 'Generated scratch data. No product index change or production capacity claim.',
        };
        writeFileSync(
          resolve(import.meta.dirname, '../../docs/06-delivery/evidence/M5-recall.json'),
          JSON.stringify(evidence, null, 2) + '\n',
        );
        process.stdout.write(JSON.stringify(evidence) + '\n');
      } finally {
        try {
          if (created) await client.query(`drop schema "${schema}" cascade`);
        } finally {
          await client.end();
        }
      }
    },
    1_200_000,
  );
});
