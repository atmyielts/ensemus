// Filtered recall of approximate vector search against exact, under ACL filters (ADR-029 D6 addendum).
// Not part of CI: it needs a disposable PostgreSQL with pgvector 0.8 or later and CREATE on the database.
//
//   ENSEMUS_RECALL_DATABASE_URL=postgres://user:pass@host:5432/scratch \
//   ENSEMUS_RECALL_ALLOW_SCRATCH=1 pnpm measure:knowledge-recall
//
// Optional: ENSEMUS_RECALL_SIZES=10000,50000,200000 (vectors per tenant), ENSEMUS_RECALL_DIMENSION=384
// (must be a width in HNSW_INDEXED_DIMENSIONS), ENSEMUS_RECALL_SAMPLES=50.
//
// It mirrors production on generated data: the same partial expression index as migration 0711, the same
// cast in the ORDER BY, the ACL as a hashed `IN (subquery)` like knowledge.readable_source_ids, a second
// tenant in the same index, and the same transaction-local settings retrieval uses. It writes JSON
// evidence to docs/06-delivery/evidence/M5-recall.json and fails if any approximate configuration falls
// below TARGET_FILTERED_RECALL_AT_10. No product table is read or written; its one schema is dropped in
// finally.
import { randomUUID } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import pg from 'pg';
import { describe, expect, it } from 'vitest';
import {
  EXACT_VECTOR_SEARCH_MAX_ROWS,
  HNSW_INDEXED_DIMENSIONS,
  HNSW_SEARCH_SETTINGS,
  TARGET_FILTERED_RECALL_AT_10,
  vectorSearchMode,
} from '@ensemus/domain/knowledge';

const DIMENSION = Number(process.env.ENSEMUS_RECALL_DIMENSION ?? 384);
const TENANT_SIZES = (process.env.ENSEMUS_RECALL_SIZES ?? '10000,50000,200000')
  .split(',')
  .map(Number);
/** Percent of a tenant's sources one person may read. 0.5% and 1% of small tenants fall to exact. */
const SELECTIVITIES = [0.5, 1, 10, 50, 100];
const SOURCES = 1_000;
const WARMUP = 5;
const SAMPLES = Number(process.env.ENSEMUS_RECALL_SAMPLES ?? 50);
const K = 10;
const schema = `knowledge_recall_${randomUUID().replaceAll('-', '')}`;
// Only identifiers generated by this file enter SQL text. Values always travel as parameters.
const table = `"${schema}"."items"`;
const acl = `"${schema}"."acl"`;
const enabled = process.env.ENSEMUS_RECALL_ALLOW_SCRATCH === '1';
const url = process.env.ENSEMUS_RECALL_DATABASE_URL;

type Sample = {
  rowsPerTenant: number;
  aclPercent: number;
  authorizedRows: number;
  productionMode: 'exact' | 'approximate';
  recallAt10: number;
  minRecallAt10: number;
  exact: ReturnType<typeof latency>;
  hnsw: ReturnType<typeof latency>;
};

function latency(values: number[]) {
  const sorted = values.toSorted((a, b) => a - b);
  const at = (p: number) =>
    sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * p) - 1)] ?? 0;
  return { samples: sorted.length, p50Ms: at(0.5), p95Ms: at(0.95) };
}

function queryVector(seed: number) {
  let state = seed;
  return JSON.stringify(
    Array.from({ length: DIMENSION }, () => {
      state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
      return state / 2147483647.5 - 1;
    }),
  );
}

describe('approximate versus exact vector recall under an ACL filter', () => {
  it.skipIf(!enabled || !url)(
    'measures generated data in an isolated scratch schema and writes JSON evidence',
    async () => {
      const index = HNSW_INDEXED_DIMENSIONS[DIMENSION];
      if (!index) throw new Error(`ENSEMUS_RECALL_DIMENSION must be one of the indexed widths`);
      const cast = `public.${index.type}(${DIMENSION})`;
      const client = new pg.Client({ connectionString: url });
      await client.connect();
      const samples: Sample[] = [];
      let created = false;
      try {
        const version = await client.query<{ extversion: string }>(
          "select extversion from pg_extension where extname='vector'",
        );
        expect(version.rows[0]?.extversion).toMatch(/^0\.(?:[89]|[1-9]\d)\.|^[1-9]\d*\./);
        await client.query(`create schema "${schema}"`);
        created = true;
        await client.query(
          `create table ${table} (id bigserial primary key, tenant integer not null, source integer not null,
             dimension integer not null, embedding public.vector not null)`,
        );
        // Who may read which source: one row per readable source, for the one person measured.
        await client.query(
          `create table ${acl} (tenant integer not null, source integer not null, primary key (tenant, source))`,
        );
        const where = `tenant = $1 and dimension = ${DIMENSION}
          and source in (select a.source from ${acl} a where a.tenant = $1)`;
        const exactQuery = `select id::text from ${table} where ${where}
          order by embedding <=> $2::public.vector limit ${K}`;
        const approximateQuery = `select id::text from ${table} where ${where}
          order by (embedding::${cast}) <=> ($2::${cast}) limit ${K}`;
        const run = async (approximate: boolean, vector: string) => {
          await client.query('begin');
          try {
            if (approximate) {
              await client.query(
                `select set_config('hnsw.iterative_scan', $1, true), set_config('hnsw.ef_search', $2, true),
                        set_config('hnsw.max_scan_tuples', $3, true), set_config('hnsw.scan_mem_multiplier', $4, true)`,
                [
                  HNSW_SEARCH_SETTINGS.iterativeScan,
                  String(HNSW_SEARCH_SETTINGS.efSearch),
                  String(HNSW_SEARCH_SETTINGS.maxScanTuples),
                  String(HNSW_SEARCH_SETTINGS.scanMemMultiplier),
                ],
              );
            } else {
              await client.query('set local enable_indexscan = off');
            }
            const start = performance.now();
            const result = await client.query<{ id: string }>(
              approximate ? approximateQuery : exactQuery,
              [1, vector],
            );
            const ms = performance.now() - start;
            await client.query('commit');
            return { ids: result.rows.map((row) => row.id), ms };
          } catch (error) {
            await client.query('rollback');
            throw error;
          }
        };
        for (const size of TENANT_SIZES) {
          await client.query(`drop index if exists "${schema}"."${index.index}"`);
          await client.query(`truncate ${table} restart identity`);
          // Two tenants share one index, as they do in production. Vectors are generated from hashes.
          await client.query(
            `insert into ${table} (tenant, source, dimension, embedding)
          select tenant, n % ${SOURCES}, ${DIMENSION},
                 array(select ((('x'||substr(md5(tenant::text||':'||n::text||':'||d::text),1,8))::bit(32)::bigint)::double precision / 2147483647.5) - 1
                         from generate_series(1,${DIMENSION}) d)::public.vector
            from generate_series(1,$1::integer) n cross join generate_series(1,2) tenant`,
            [size],
          );
          await client.query(
            `create index "${index.index}" on ${table} using hnsw ((embedding::${cast}) public.${index.type}_cosine_ops) where dimension = ${DIMENSION}`,
          );
          await client.query(`analyze ${table}`);
          for (const percent of SELECTIVITIES) {
            await client.query(`truncate ${acl}`);
            const readable = Math.max(1, Math.round((SOURCES * percent) / 100));
            await client.query(
              `insert into ${acl} select 1, s from generate_series(0, $1::integer - 1) s`,
              [readable],
            );
            await client.query(`analyze ${acl}`);
            const authorizedRows = Math.round((size * readable) / SOURCES);
            // The approximate plan must use the index; otherwise this measures nothing.
            await client.query('begin');
            try {
              await client.query("select set_config('hnsw.iterative_scan', 'strict_order', true)");
              const plan = await client.query(`explain (format json) ${approximateQuery}`, [
                1,
                queryVector(1),
              ]);
              expect(JSON.stringify(plan.rows)).toContain(index.index);
            } finally {
              await client.query('rollback');
            }
            const exactMs: number[] = [],
              hnswMs: number[] = [],
              recall: number[] = [];
            for (let i = 0; i < WARMUP + SAMPLES; i++) {
              const vector = queryVector(1000 + i);
              const exact = await run(false, vector);
              const approximate = await run(true, vector);
              expect(new Set(approximate.ids).size).toBe(approximate.ids.length);
              if (i >= WARMUP && exact.ids.length) {
                const truth = new Set(exact.ids);
                recall.push(
                  approximate.ids.filter((id) => truth.has(id)).length / exact.ids.length,
                );
                exactMs.push(exact.ms);
                hnswMs.push(approximate.ms);
              }
            }
            samples.push({
              rowsPerTenant: size,
              aclPercent: percent,
              authorizedRows,
              productionMode: vectorSearchMode({ dimension: DIMENSION, authorizedRows }),
              recallAt10: recall.reduce((a, b) => a + b, 0) / Math.max(1, recall.length),
              minRecallAt10: Math.min(...recall),
              exact: latency(exactMs),
              hnsw: latency(hnswMs),
            });
          }
        }
        const evidence = {
          measuredAt: new Date().toISOString(),
          vectorVersion: version.rows[0]!.extversion,
          dimension: DIMENSION,
          tenants: 2,
          sourcesPerTenant: SOURCES,
          exactBelowAuthorizedRows: EXACT_VECTOR_SEARCH_MAX_ROWS,
          targetRecallAt10: TARGET_FILTERED_RECALL_AT_10,
          settings: HNSW_SEARCH_SETTINGS,
          samples,
          note: 'Generated scratch data. Production uses exact search wherever productionMode is exact.',
        };
        writeFileSync(
          resolve(import.meta.dirname, '../../docs/06-delivery/evidence/M5-recall.json'),
          JSON.stringify(evidence, null, 2) + '\n',
        );
        process.stdout.write(JSON.stringify(evidence) + '\n');
        // Only configurations production would actually search approximately are held to the target.
        for (const sample of samples.filter((s) => s.productionMode === 'approximate'))
          expect(
            sample.recallAt10,
            `${sample.rowsPerTenant} rows at ${sample.aclPercent}%`,
          ).toBeGreaterThanOrEqual(TARGET_FILTERED_RECALL_AT_10);
      } finally {
        try {
          if (created) await client.query(`drop schema "${schema}" cascade`);
        } finally {
          await client.end();
        }
      }
    },
    3_600_000,
  );
});
